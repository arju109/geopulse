CREATE WAREHOUSE IF NOT EXISTS GEOPULSE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS GEOPULSE;
CREATE SCHEMA IF NOT EXISTS GEOPULSE.RAW;
USE SCHEMA GEOPULSE.RAW;

CREATE OR REPLACE TABLE STORES (
  store_id STRING, store_name STRING,
  latitude FLOAT, longitude FLOAT,
  geog GEOGRAPHY
);

CREATE OR REPLACE TABLE RAW_PINGS (
  device_id STRING, latitude FLOAT, longitude FLOAT,
  ping_ts TIMESTAMP_NTZ, geog GEOGRAPHY
);